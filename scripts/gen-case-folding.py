"""Generates src/library/case_folding_table.h, the Unicode simple case folding table of libddb's
case-insensitive name matching (utf8::foldCase).

Simple case folding is the mappings of CaseFolding.txt with status C (common) and S (simple):
each maps one code point to one code point, so a folded string has as many code points as the
original. The F (full) mappings (e.g. U+00DF to "ss") and the T (Turkic) ones are left out.

Usage:
    python3 -I scripts/gen-case-folding.py <CaseFolding.txt> [<output>]

CaseFolding.txt is published at https://www.unicode.org/Public/<version>/ucd/CaseFolding.txt.
The table in the repository was generated from CaseFolding-16.0.0.txt
(sha256 6f1f9c588eb4a5c718d9e8f93b782685e5c7fec872cf05e8e6878053599e09bb).
"""

import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = ROOT / "src" / "library" / "case_folding_table.h"
PAIRS_PER_LINE = 4


def parse(text: str) -> dict[int, int]:
    folding: dict[int, int] = {}
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        code, status, mapping = (field.strip() for field in line.split(";")[:3])
        if status not in ("C", "S"):
            continue
        targets = mapping.split()
        if len(targets) != 1:
            sys.exit(f"status {status} maps U+{code} to {len(targets)} code points; expected 1")
        folding[int(code, 16)] = int(targets[0], 16)
    return folding


def ascii_with_non_ascii_variants(folding: dict[int, int]) -> str:
    """The ASCII characters that fold to the same code point as some non-ASCII one (e.g. 'k' and
    U+212A KELVIN SIGN)."""
    fold = lambda cp: folding.get(cp, cp)  # noqa: E731
    non_ascii_targets = {to for frm, to in folding.items() if frm >= 0x80}
    return "".join(chr(c) for c in range(0x80) if fold(c) in non_ascii_targets)


def main() -> int:
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    source = pathlib.Path(sys.argv[1])
    output = pathlib.Path(sys.argv[2]) if len(sys.argv) == 3 else DEFAULT_OUTPUT
    data = source.read_bytes()
    text = data.decode("utf-8")
    version = re.search(r"CaseFolding-([0-9.]+)\.txt", text)
    if version is None:
        sys.exit(f"{source}: no 'CaseFolding-<version>.txt' header")

    folding = parse(text)
    pairs = [f"{{0x{frm:04X}, 0x{to:04X}}}" for frm, to in sorted(folding.items())]
    rows = [", ".join(pairs[i:i + PAIRS_PER_LINE]) for i in range(0, len(pairs), PAIRS_PER_LINE)]
    ascii_variants = ascii_with_non_ascii_variants(folding)

    header = f"""/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at https://mozilla.org/MPL/2.0/. */

// Generated by scripts/gen-case-folding.py from CaseFolding-{version.group(1)}.txt
// (sha256 {hashlib.sha256(data).hexdigest()}).
// Do not edit: run the script.
//
// Unicode simple case folding: the CaseFolding.txt mappings with status C and S, sorted by
// code point. Private to utf8.cpp.

#ifndef CASE_FOLDING_TABLE_H
#define CASE_FOLDING_TABLE_H

namespace ddb::utf8::detail {{

struct CaseFoldingPair {{
    char32_t from;
    char32_t to;
}};

inline constexpr char kCaseFoldingVersion[] = "{version.group(1)}";

// The ASCII characters that also fold to the same code point as a non-ASCII character
inline constexpr char kAsciiWithNonAsciiFoldVariants[] = "{ascii_variants}";

// clang-format off
inline constexpr CaseFoldingPair kCaseFolding[] = {{
{chr(10).join("    " + row + "," for row in rows)}
}};
// clang-format on

}}  // namespace ddb::utf8::detail

#endif  // CASE_FOLDING_TABLE_H
"""
    output.write_text(header, encoding="utf-8", newline="\n")
    print(f"{output}: {len(folding)} mappings, Unicode {version.group(1)}, ASCII with non-ASCII variants: {ascii_variants!r}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
